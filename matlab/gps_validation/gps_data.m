function entries = gps_data()
% gps_data.m
% Master GPS validation file list for this project.
%
% Returns a struct array with fields:
%   url        — S3 download URL
%   file_name  — local filename to save as
%   ekf_id     — corresponding EKF flight_id in _data_clean/
%   notes      — brief description of source and relevance
%
% Scope: on-board Featherweight GPS CSV files only.
% Combined ground-log files (multi-flight) and XLSX files are excluded
% here — they require flight-window splitting and are handled separately.
%
% Groups:
%   1) Madcow Adventurer, 17-Apr-2021 (Raven altimeter flights)
%      Two individual on-board GPS files, one per flight. These are the
%      cleanest GPS sources in the archive: single-flight, on-board, CSV.
%      Correspond to T1-C (J530 Raven) and the paired J510W Raven flight —
%      both show EKF post-apogee divergence. GPS provides an independent
%      apogee reference to confirm ascent-phase correctness.

entries = struct( ...
    'url',       {}, ...
    'file_name', {}, ...
    'ekf_id',    {}, ...
    'notes',     {} ...
);

% -----------------------------------------------------------------------
% 1) Madcow Adventurer — 17 Apr 2021 on-board GPS
% -----------------------------------------------------------------------
entries(end+1) = struct( ...
    'url',       'https://dofprobucket2.s3.us-east-2.amazonaws.com/Adventurer/20210417_Adventurer_J510W_1_GPS.csv', ...
    'file_name', '20210417_Adventurer_J510W_1_GPS.csv', ...
    'ekf_id',    'raven_csv_20210417_adventurer_j510w_1_raven', ...
    'notes',     'On-board Featherweight GPS, J510W flight, 17-Apr-2021' ...
);

entries(end+1) = struct( ...
    'url',       'https://dofprobucket2.s3.us-east-2.amazonaws.com/Adventurer/20210417_Adventurer_J530_1_GPS.csv', ...
    'file_name', '20210417_Adventurer_J530_1_GPS.csv', ...
    'ekf_id',    'raven_csv_20210417_adventurer_j530_1_raven', ...
    'notes',     'On-board Featherweight GPS, J530 flight (T1-C), 17-Apr-2021' ...
);

end
